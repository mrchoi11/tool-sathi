export function getToolBySlug(slug: string): Tool | undefined {
  return tools.find(t => t.slug === slug);
}

export function getToolsByCategory(category: ToolCategory): Tool[] {
  return tools.filter(t => t.category === category);
}

export function getFeaturedTools(): Tool[] {
  return tools.filter(t => t.isFeatured && t.status === 'active');
}

export function getActiveTools(): Tool[] {
  return tools.filter(t => t.status === 'active');
}

export function searchTools(query: string): Tool[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return tools.filter(t => {
    if (t.status !== 'active') return false;
    return (
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.keywords.some(k => k.includes(q)) ||
      t.category.includes(q) ||
      (t.inputFormats && t.inputFormats.some(f => f.includes(q))) ||
      (t.outputFormats && t.outputFormats.some(f => f.includes(q)))
    );
  });
}

export function getCategoryInfo(id: ToolCategory): ToolCategoryInfo | undefined {
  return categories.find(c => c.id === id);
}
