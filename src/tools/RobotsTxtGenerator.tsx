import React, { useState } from 'react';
import { Bot, Copy, Download, Check } from 'lucide-react';
import { saveAs } from 'file-saver';
import './tools.css';

export default function RobotsTxtGenerator() {
  const [sitemapUrl, setSitemapUrl] = useState<string>('https://toolsathi.com/sitemap.xml');
  const [allowAll, setAllowAll] = useState<boolean>(true);
  const [disallowPaths, setDisallowPaths] = useState<string>('/admin/\n/private/\n/api/');
  const [copied, setCopied] = useState<boolean>(false);

  const generateRobots = (): string => {
    let content = '# Robots.txt generated by ToolSathi\nUser-agent: *\n';
    if (allowAll) {
      content += 'Allow: /\n';
    }
    const paths = disallowPaths.split('\n').map(p => p.trim()).filter(Boolean);
    paths.forEach(p => {
      content += `Disallow: ${p}\n`;
    });

    if (sitemapUrl.trim()) {
      content += `\nSitemap: ${sitemapUrl.trim()}\n`;
    }
    return content;
  };

  const robotsOutput = generateRobots();

  const handleCopy = () => {
    navigator.clipboard.writeText(robotsOutput);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([robotsOutput], { type: 'text/plain;charset=utf-8' });
    saveAs(blob, 'robots.txt');
  };

  return (
    <div className="tool-container">
      <div className="tool-card-panel">
        <h3 style={{ fontSize: '1.15rem', marginBottom: 'var(--space-md)' }}>Robots.txt Configuration</h3>

        <div className="tool-form-grid" style={{ marginBottom: 'var(--space-lg)' }}>
          <div className="tool-field">
            <label className="tool-label">XML Sitemap URL</label>
            <input
              type="url"
              className="tool-input"
              value={sitemapUrl}
              onChange={e => setSitemapUrl(e.target.value)}
              placeholder="https://example.com/sitemap.xml"
            />
          </div>

          <div className="tool-field" style={{ justifyContent: 'center' }}>
            <label className="tool-label" style={{ cursor: 'pointer', display: 'flex', alignItems: 'center', gap: '8px' }}>
              <input
                type="checkbox"
                checked={allowAll}
                onChange={e => setAllowAll(e.target.checked)}
                style={{ width: '18px', height: '18px', accentColor: 'var(--color-primary)' }}
              />
              Allow all public pages (Allow: /)
            </label>
          </div>
        </div>

        <div className="tool-field" style={{ marginBottom: 'var(--space-xl)' }}>
          <label className="tool-label">Disallowed Paths (one per line)</label>
          <textarea
            className="tool-textarea"
            style={{ height: '100px' }}
            value={disallowPaths}
            onChange={e => setDisallowPaths(e.target.value)}
          />
        </div>

        <div className="tool-result-header" style={{ marginBottom: 'var(--space-md)' }}>
          <span className="tool-result-title">Generated robots.txt</span>
          <div style={{ display: 'flex', gap: 'var(--space-sm)' }}>
            <button
              type="button"
              onClick={handleCopy}
              className="btn btn-ghost btn-sm"
              style={{ display: 'flex', alignItems: 'center', gap: '4px' }}
            >
              {copied ? <Check size={14} color="#10b981" /> : <Copy size={14} />} {copied ? 'Copied' : 'Copy'}
            </button>
            <button
              type="button"
              onClick={handleDownload}
              className="btn btn-primary btn-sm"
              style={{ display: 'flex', alignItems: 'center', gap: '4px' }}
            >
              <Download size={14} /> Download robots.txt
            </button>
          </div>
        </div>

        <textarea
          readOnly
          className="tool-textarea"
          value={robotsOutput}
          style={{ height: '180px', background: 'var(--color-bg)' }}
        />
      </div>
    </div>
  );
}
